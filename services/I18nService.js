class I18nService {
    constructor() {
        this.locales = LOCALES;
    }

    static getAllLocales() {
        return LOCALES;
    }

    getLocaleMetadata() {
        return this.locales;
    }

    getLanguage() {
        let lang = navigator.language;
        if (typeof chrome !== 'undefined' && chrome.i18n && chrome.i18n.getUILanguage) {
            lang = chrome.i18n.getUILanguage();
        }
        return lang;
    }

    getActiveLocale() {
        const lang = this.getLanguage();
        const localeEntry = Object.entries(this.locales).find(([code]) => {
            if (code === 'zh-CN' && (lang === 'zh-CN' || lang === 'zh-SG')) {
                return true;
            }
            if (code === 'zh-TW' && lang.startsWith('zh')) {
                return true;
            }
            if (lang === code) {
                return true;
            }
            if (!code.includes('-')) {
                return lang.startsWith(code);
            }
            return false;
        });

        const [code, metadata] = localeEntry || ['en', this.locales['en']];
        return {
            code,
            label: metadata.label,
            direction: metadata.direction,
            strings: metadata.strings
        };
    }

    isRTL() {
        return this.getActiveLocale().direction === 'rtl';
    }

    getText(key, values = {}) {
        const locale = this.getActiveLocale();
        let text = locale.strings[key] || this.locales.en.strings[key] || key;
        Object.entries(values || {}).forEach(([name, value]) => {
            text = text.replaceAll(`{${name}}`, String(value));
        });
        return text;
    }

    localizePage() {
        const locale = this.getActiveLocale();
        const { strings: t } = locale;
        if (document.documentElement) {
            document.documentElement.lang = locale.code;
            document.documentElement.dir = locale.direction;
        }
        const elements = document.querySelectorAll('[data-i18n]');
        elements.forEach(el => {
            const key = el.getAttribute('data-i18n');
            const text = t[key] || this.locales.en.strings[key];
            if (text) {
                if (el.tagName === 'INPUT' && el.getAttribute('placeholder')) {
                    el.placeholder = text;
                } else {
                    el.textContent = text;
                }
            }
        });

        document.querySelectorAll('[data-i18n-title]').forEach(el => {
            el.title = this.getText(el.getAttribute('data-i18n-title'));
        });
        
        // Update document title if data-i18n is present on body or separate element, 
        // but often title is hard to target via selector in body. 
        // We can check if title element has it.
        const titleEl = document.querySelector('title[data-i18n]');
        if (titleEl) {
            const key = titleEl.getAttribute('data-i18n');
            const text = t[key] || this.locales.en.strings[key];
            if (text) document.title = text;
        }
    }
}

// Make it available globally
if (typeof window !== 'undefined') {
    window.I18nService = I18nService;
}

